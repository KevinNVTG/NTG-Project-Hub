create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();
drop trigger if exists projects_assign_number on public.projects;
create trigger projects_assign_number before insert on public.projects for each row execute function public.assign_project_number();
drop trigger if exists customers_set_created_by on public.customers;
create trigger customers_set_created_by before insert on public.customers for each row execute function public.set_created_by();
drop trigger if exists profiles_updated_at on public.profiles;
create trigger profiles_updated_at before update on public.profiles for each row execute function public.set_updated_at();
drop trigger if exists customers_updated_at on public.customers;
