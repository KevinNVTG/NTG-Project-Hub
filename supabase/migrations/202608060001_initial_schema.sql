-- NTG Project Hub v0.1 initial schema
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text,
  role text not null default 'owner' check (role in ('owner','administrator','estimator','project_manager','accounting')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  customer_type text not null default 'residential' check (customer_type in ('residential','commercial')),
  first_name text,
  last_name text,
  company_name text,
  email text,
  phone text,
  billing_address text,
  notes text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.project_sequences (
  year integer primary key,
  current_value integer not null default 0
);

create table if not exists public.projects (
  id uuid primary key default gen_random_uuid(),
  project_number text unique,
  customer_id uuid references public.customers(id) on delete set null,
  project_name text not null,
  project_address text,
  project_type text not null default 'residential' check (project_type in ('residential','commercial')),
  status text not null default 'lead' check (status in ('lead','estimating','awarded','active','on_hold','complete','closed')),
  contract_amount numeric(12,2) not null default 0,
  notes text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.company_settings (
  id uuid primary key default gen_random_uuid(),
  company_name text not null,
  phone text,
  email text,
  website text,
  address text,
  license_c19 text,
  license_c20 text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  project_id uuid references public.projects(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.assign_project_number()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  y integer := extract(year from now())::integer;
  next_value integer;
begin
  if new.project_number is null or btrim(new.project_number) = '' then
    insert into public.project_sequences(year, current_value)
    values (y, 1)
    on conflict (year) do update set current_value = public.project_sequences.current_value + 1
    returning current_value into next_value;
    new.project_number := 'PRJ-' || right(y::text, 2) || '-' || lpad(next_value::text, 4, '0');
  end if;
  if new.created_by is null then new.created_by := auth.uid(); end if;
  return new;
end;
$$;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles(id, email, full_name, role)
  values (new.id, new.email, coalesce(new.raw_user_meta_data->>'full_name',''), 'owner')
  on conflict (id) do nothing;
  return new;
end;
$$;

create or replace function public.set_created_by()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.created_by is null then new.created_by := auth.uid(); end if;
  return new;
end;
$$;

