create policy "authenticated profiles read" on public.profiles for select to authenticated using (true);
create policy "users update own profile" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());
create policy "authenticated customers all" on public.customers for all to authenticated using (true) with check (true);
create policy "authenticated projects all" on public.projects for all to authenticated using (true) with check (true);
create policy "authenticated company settings read" on public.company_settings for select to authenticated using (true);
create policy "owners company settings update" on public.company_settings for update to authenticated using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role in ('owner','administrator'))) with check (true);
create policy "authenticated activity read" on public.activity_logs for select to authenticated using (true);
create policy "authenticated activity insert" on public.activity_logs for insert to authenticated with check (user_id is null or user_id = auth.uid());

